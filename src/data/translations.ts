export function t(keyPath: string, lang: Language): string {
  const parts = keyPath.split('.');
  let curr: any = translations;
  for (const part of parts) {
    if (curr && curr[part]) {
      curr = curr[part];
    } else {
      return keyPath;
    }
  }
  if (curr && typeof curr === 'object') {
    return curr[lang] || curr.gu || curr.en || keyPath;
  }
  return String(curr);
}
